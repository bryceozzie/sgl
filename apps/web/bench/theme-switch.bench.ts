function median(values: readonly number[]): number {
  const s = [...values].sort((a, b) => a - b);
  const m = Math.floor(s.length / 2);
  return s.length % 2 === 1 ? s[m]! : (s[m - 1]! + s[m]!) / 2;
}

function fmt(values: readonly number[]): string {
  return `${median(values).toFixed(1)} (${Math.min(...values).toFixed(1)}–${Math.max(...values).toFixed(1)})`;
}

const sleep = (ms: number): Promise<void> => new Promise((resolve) => setTimeout(resolve, ms));

async function until(what: string, test: () => boolean, timeoutMs = 60_000): Promise<void> {
  const start = performance.now();
  while (!test()) {
    if (performance.now() - start > timeoutMs) throw new Error(`timed out waiting for ${what}`);
    await sleep(5);
  }
}

const sum = (xs: readonly number[]): number => xs.reduce((a, b) => a + b, 0);

interface Harness {
  readonly pipeline: Pipeline;
  readonly view: EditorView;
  readonly wrapper: SVGGElement;
  /** Durations of every `innerHTML` swap into the wrapper since the last reset. */
  readonly swaps: number[];
  /** Durations of every `<style>` text swap inside the wrapper since the last reset. */
  readonly styleSwaps: number[];
  /** Every paint into the canvas, of either kind, since the last reset. */
  paints(): number;
  /** How many layout requests the worker host received since the last reset. */
  layoutRequests(): number;
  resetCounters(): void;
  dispose(): void;
}

/**
 * The layout worker, in the page: the real `createWorkerRuntime` behind the
 * real `createWorkerHost`, messages structured-cloned and delivered on a
 * later task as `postMessage` would. Not a real `Worker` because `vi.mock`
 * (the breakdown's timing wrappers, `@sgl/core` included) reaches a worker's
 * module graph too, where Vitest's mocker does not exist, and the worker then
 * never answers. Layout is not on a theme switch's path at all: every run
 * asserts no layout request was made.
 */
function inPageWorker(): Worker {
  const registry = new EngineRegistry();
  registry.register(gridEngine);
  const listeners: ((ev: MessageEvent) => void)[] = [];
  const runtime = createWorkerRuntime(registry, {
    post: (message: WorkerToHost) => {
      const data = structuredClone(message);
      setTimeout(() => {
        for (const listener of listeners) listener({ data } as MessageEvent);
      }, 0);
    },
  });
  const worker = {
    addEventListener: (_type: 'message', listener: (ev: MessageEvent) => void) => listeners.push(listener),
    postMessage: (message: HostToWorker) => {
      const data = structuredClone(message);
      setTimeout(() => runtime.receive(data), 0);
    },
    terminate: () => {
      listeners.length = 0;
    },
  };
  return worker as unknown as Worker;
}

/** The real pipeline, editor and canvas, as `App` wires them (minus boot, the
 *  toolbar and the panels). */
async function mountApp(source: string): Promise<Harness> {
  const root = document.createElement('div');
  root.style.cssText = 'position:fixed;left:0;top:0;width:1600px;height:900px;display:flex;';
  document.body.appendChild(root);
  const editorHost = document.createElement('div');
  editorHost.style.cssText = 'width:600px;height:900px;overflow:auto;';
  const canvasHost = document.createElement('div');
  canvasHost.style.cssText = 'width:1000px;height:900px;';
  root.append(editorHost, canvasHost);

  const measurer = new CanvasMeasurer();
  const realHost = createWorkerHost(inPageWorker, {
    measure: (runs, box) => measurer.layoutRunsAsync(runs as readonly StyledRun[], box as BoxConstraints),
  });
  let layoutRequests = 0;
  const layoutHost: typeof realHost = {
    run(...args) {
      layoutRequests += 1;
      return realHost.run(...args);
    },
    dispose: () => realHost.dispose(),
  };
  const pipeline = createPipeline({ measurer, host: layoutHost, metrics: APP_METRICS, defaultEngineId: 'sgl.grid', defaultThemeId: LIGHT }, source);
  // `Editor`'s `updateListener` calls `pipeline.setDocument(tree, source)` by
  // property lookup, so timing it here splits the dispatch into CodeMirror's
  // share and the pipeline's, with `Editor.tsx` unchanged.
  const setDocument = pipeline.setDocument.bind(pipeline);
  (pipeline as { setDocument: Pipeline['setDocument'] }).setDocument = timed(setDocument, () => calls.setDocument);

  let view: EditorView | null = null;
  mountPreact(h(Editor, { pipeline, onView: (v: EditorView | null) => (view = v) }), editorHost);
  mountPreact(h(Canvas, { pipeline }), canvasHost);

  const wrapper = canvasHost.querySelector<SVGGElement>('g.rendered');
  if (wrapper === null) throw new Error('Canvas did not mount its wrapper <g>.');
  await until('the editor view', () => view !== null);

  // Time the canvas's two kinds of paint at the DOM itself, so `Canvas.tsx`
  // and `canvas/paint.ts` run unchanged: the `innerHTML` swap as an own
  // accessor on the wrapper, and the `<style>` text swap at `Node.prototype`'s
  // `textContent` setter, counted only for a `<style>` inside the wrapper.
  const nativeHtml = Object.getOwnPropertyDescriptor(Element.prototype, 'innerHTML')!;
  const swaps: number[] = [];
  Object.defineProperty(wrapper, 'innerHTML', {
    configurable: true,
    get(this: Element) {
      return nativeHtml.get!.call(this);
    },
    set(this: Element, value: string) {
      const t = performance.now();
      nativeHtml.set!.call(this, value);
      swaps.push(performance.now() - t);
    },
  });
  const nativeText = Object.getOwnPropertyDescriptor(Node.prototype, 'textContent')!;
  const styleSwaps: number[] = [];
  Object.defineProperty(Node.prototype, 'textContent', {
    configurable: true,
    get(this: Node) {
      return nativeText.get!.call(this);
    },
    set(this: Node, value: string | null) {
      const counted = this instanceof SVGStyleElement && wrapper.contains(this);
      const t = performance.now();
      nativeText.set!.call(this, value);
      if (counted) styleSwaps.push(performance.now() - t);
    },
  });

  try {
    await until('the first live render', () => pipeline.lastGood.peek() !== null && wrapper.getAttribute('data-origin') === 'live', 120_000);
  } catch (err) {
    const state = {
      pipelineError: pipeline.pipelineError.peek(),
      errors: pipeline.diags.peek().filter((d) => d.severity === 'error').slice(0, 3),
      measured: Object.keys(pipeline.table.peek()).length,
      layout: pipeline.layout.peek() !== null,
      inFlight: pipeline.inFlight.peek(),
    };
    throw new Error(`${String(err)}: ${JSON.stringify(state)}`);
  }
  const paints = (): number => swaps.length + styleSwaps.length;
  // Boot can lay out more than once (the font-gated pre-measure, DD-08 §5);
  // let all of it finish before the first pick.
  await quiet(pipeline, paints, 1000);

  return {
    pipeline,
    view: view!,
    wrapper,
    swaps,
    styleSwaps,
    paints,
    layoutRequests: () => layoutRequests,
    resetCounters() {
      swaps.length = 0;
      styleSwaps.length = 0;
      layoutRequests = 0;
      for (const k of ['buildAst', 'resolve', 'compile', 'resolveTheme', 'styleGraph', 'render', 'paintOnly', 'premeasure', 'setDocument'] as const) calls[k] = [];
      calls.premeasureDone = 0;
    },
    dispose() {
      mountPreact(null, editorHost);
      mountPreact(null, canvasHost);
      pipeline.dispose();
      realHost.dispose();
      root.remove();
      Object.defineProperty(Node.prototype, 'textContent', nativeText);
    },
  };
}

/** The Theme ▾ picker's `select(id)`, verbatim (`src/toolbar/ThemePicker.tsx`). */
function pick(app: Harness, id: string): void {
  selectTheme(app.pipeline, id, (change) => dispatchTextChange(app.view, change));
}

