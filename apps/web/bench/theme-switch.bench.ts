function timed<A extends unknown[], R>(fn: (...args: A) => R, into: () => number[], after?: (end: number) => void): (...args: A) => R {
  return (...args: A): R => {
    const t = performance.now();
    try {
      return fn(...args);
    } finally {
      const end = performance.now();
      into().push(end - t);
      after?.(end);
    }
  };
}

