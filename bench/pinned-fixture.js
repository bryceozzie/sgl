// The pure half of `bench/generate-pinned-fixture.js` (DD-12 §12 item 5), with
// no Node imports, so `packages/layout-std/test/pinned-fixture.test.ts` can run
// the same functions over the same inputs and check the committed
// `corpus/layout/forty-three-pinned.sgl` against them.

/**
 * Every visible node's pin, from a layout: its frame's top-left relative to
 * the top-left of its parent's content box (DD-12 H2) — the parent's frame
 * inset by its padding — or, at the root, the frame's own top-left. Rounded
 * to whole pixels, so the document reads as an author would write it.
 */
export function gridPins(input, result) {
  const pins = new Map();
  for (const id of input.graph.order) {
    const node = input.graph.nodes[id];
    const frame = result.nodes[id]?.frame;
    if (node === undefined || frame === undefined) continue;
    let x = frame.x;
    let y = frame.y;
    if (node.parent !== null) {
      const parent = result.nodes[node.parent].frame;
      const padding = input.sizing[node.parent].padding;
      x = frame.x - parent.x - padding[3];
      y = frame.y - parent.y - padding[0];
    }
    pins.set(id, { x: Math.round(x), y: Math.round(y) });
  }
  return pins;
}

const HEADER = [
  '// MVP criterion 1 for `fixed` (DD-12 §12 item 5): `forty-three-level.sgl` with',
  "// a `@pin` on every node, taken once from its `grid` layout. Generated by",
  '// `bench/generate-pinned-fixture.js`; do not hand-edit. Every node is pinned,',
  '// so under `fixed` it lays out with no diagnostic; under an engine without',
  '// pins it would be one SGL4021 per node.',
];

/**
 * `source` (`corpus/forty-three-level.sgl`) with its leading comment replaced
 * by `HEADER`, `@layout: { engine: fixed }` after `@title`, and a `@pin` on
 * every node: `name: {}` becomes `name: { @pin: { x, y } }`, and a
 * container's opening line `name: {` is followed by a `@pin` line. Only the
 * shapes that document uses are recognised; anything else is copied.
 */
export function pinnedSource(source, pins) {
  const lines = source.split('\n');
  let i = 0;
  while (i < lines.length && lines[i].startsWith('//')) i += 1;
  const out = [...HEADER];
  const path = [];
  const pin = (id) => {
    const p = pins.get(id);
    if (p === undefined) throw new Error(`pinned-fixture: no pin for '${id}'.`);
    return `@pin: { x: ${p.x}, y: ${p.y} }`;
  };
  for (; i < lines.length; i += 1) {
    const line = lines[i];
    const leaf = /^(\s*)([\w-]+): \{\}\s*$/.exec(line);
    const open = /^(\s*)([\w-]+): \{\s*$/.exec(line);
    if (leaf !== null) {
      out.push(`${leaf[1]}${leaf[2]}: { ${pin([...path, leaf[2]].join('.'))} }`);
    } else if (open !== null) {
      path.push(open[2]);
      out.push(line, `${open[1]}  ${pin(path.join('.'))}`);
    } else if (/^\s*\}\s*$/.test(line)) {
      path.pop();
      out.push(line);
    } else if (/^@title:/.test(line)) {
      out.push(line, '@layout: { engine: fixed }');
    } else {
      out.push(line);
    }
  }
  return out.join('\n');
}
