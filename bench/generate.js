#!/usr/bin/env node
// Deterministically writes the generated corpus documents Stage G's perf bench
// and diagnostics coverage gate need. No `Math.random`, no `Date.now` (DD-00
// §3) — every byte here is a pure function of the node count, so re-running
// this script produces byte-identical output, which is what keeps these
// fixtures out of source control (bench/README.md): the shape of a 2 000-node
// document is one decision, made here, not a diff to review each time it
// changes.
//
// Run with `node bench/generate.js`. Wired into `pnpm test`/`pnpm check` (root
// package.json) so the files always exist before Vitest collects `corpus/`.

import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const corpusDir = fileURLToPath(new URL('../corpus/', import.meta.url));

/**
 * A flat scale fixture: `n` nodes in a chain (`n0 -> n1 -> n2 -> ...`), grouped
 * into containers of 10 so a scale document also exercises nesting rather than
 * one 2 000-wide root. Every 7th node carries a label with a multi-word string,
 * so measurement is exercised too, not just node/edge count.
 */
function scaleDocument(n) {
  const perContainer = 10;
  const lines = [`// Generated by bench/generate.js — ${n} nodes. Do not hand-edit.`, `@title: "Scale ${n}"`, ''];

  const containerCount = Math.ceil(n / perContainer);
  let nodeIndex = 0;
  for (let c = 0; c < containerCount; c += 1) {
    lines.push(`g${c}: {`);
    const inThisContainer = Math.min(perContainer, n - nodeIndex);
    for (let i = 0; i < inThisContainer; i += 1) {
      const label = nodeIndex % 7 === 0 ? ` { @label: "Node number ${nodeIndex}" }` : ' {}';
      lines.push(`  n${nodeIndex}:${label}`);
      nodeIndex += 1;
    }
    lines.push('}');
  }

  lines.push('');
  for (let i = 0; i < n - 1; i += 1) {
    lines.push(`g${Math.floor(i / perContainer)}.n${i} -> g${Math.floor((i + 1) / perContainer)}.n${i + 1}`);
  }
  lines.push('');
  return lines.join('\n');
}

/**
 * `SGL3005` (DD-03 §3.1) needs a wildcard cross product over `MAX_EDGE_EXPANSION`
 * (1 000, `packages/core/src/compile.ts`). 32 x 32 = 1 024 is the smallest square
 * past the ceiling, so this is the smallest document that can trip it — corpus/
 * README's "Not yet covered" note asks for exactly this, generated rather than
 * hand-typed because hand-typing 32 node declarations is not a document anyone
 * would author, it's an arithmetic fact about the ceiling.
 */
function edgeExpansionLimitDocument() {
  const width = 32;
  const lines = [
    '// expects: SGL3005 — 32 x 32 = 1024 edges, over MAX_EDGE_EXPANSION (1000).',
    '// Generated by bench/generate.js.',
    'box: {',
  ];
  for (let i = 0; i < width; i += 1) lines.push(`  n${i}: {}`);
  lines.push('}', '', 'box.* -> box.*', '');
  return lines.join('\n');
}

function write(relPath, content) {
  writeFileSync(`${corpusDir}${relPath}`, content, 'utf8');
}

mkdirSync(`${corpusDir}unresolved`, { recursive: true });

write('n50.sgl', scaleDocument(50));
write('n500.sgl', scaleDocument(500));
write('n2000.sgl', scaleDocument(2000));
write('unresolved/edge-expansion-limit.sgl', edgeExpansionLimitDocument());

console.log('bench/generate.js: wrote n50.sgl, n500.sgl, n2000.sgl, unresolved/edge-expansion-limit.sgl');
